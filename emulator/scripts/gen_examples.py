#!/usr/bin/env python3
"""Embed firmware/examples/* into the ROM as one LZSS-compressed stream.

The files are compressed together (later files reuse text of earlier ones)
and examples_install() decodes the stream into free RAM disk space (or the
TPA when the disk is too full), then creates the files from it.

Stream format (decoded by unlz in firmware/src/lib51.asm): a control byte
whose bits, LSB first, select a literal byte (1) or a back reference (0).
A back reference is two bytes: distance low 8 bits, then
(distance high 4 bits << 4) | (length - 3); distance 1..4095, length 3..18.
"""
import os, sys

src = sys.argv[1] if len(sys.argv) > 1 else 'firmware/examples'
out = sys.argv[2] if len(sys.argv) > 2 else 'firmware/build/exdata.asm'
order = ['readme.txt', 'hello.asm', 'blink.asm', 'timer.asm', 'button.asm',
         'upper.asm', 'primes.asm', 'files.asm']


def lzss(data):
    """Optimal parse: minimise 9 bits per literal, 17 bits per reference."""
    n = len(data)
    best = [(0, 0)] * n                 # longest match (length, distance)
    for i in range(n):
        lo = max(0, i - 4095)
        maxlen = min(18, n - i)
        bl, bd = 0, 0
        for j in range(i - 1, lo - 1, -1):
            k = 0
            while k < maxlen and data[j + k] == data[i + k]:
                k += 1
            if k > bl:
                bl, bd = k, i - j
                if k == maxlen:
                    break
        best[i] = (bl, bd)
    cost = [0] * (n + 1)
    step = [0] * n
    for i in range(n - 1, -1, -1):
        cost[i], step[i] = 9 + cost[i + 1], 1
        bl = best[i][0]
        for l in range(3, bl + 1):
            c = 17 + cost[i + l]
            if c < cost[i]:
                cost[i], step[i] = c, l
    outb = bytearray()
    i = 0
    while i < n:
        ctl_pos = len(outb)
        outb.append(0)
        ctl = 0
        for bit in range(8):
            if i >= n:
                break
            l = step[i]
            if l >= 3:
                d = best[i][1]
                outb.append(d & 0xFF)
                outb.append(((d >> 8) << 4) | (l - 3))
                i += l
            else:
                ctl |= 1 << bit
                outb.append(data[i])
                i += 1
        outb[ctl_pos] = ctl
    return bytes(outb)


def unlzss(comp, n):
    o = bytearray()
    p = 0
    while len(o) < n:
        ctl = comp[p]; p += 1
        for bit in range(8):
            if len(o) >= n:
                break
            if ctl >> bit & 1:
                o.append(comp[p]); p += 1
            else:
                d = comp[p] | (comp[p + 1] >> 4) << 8
                l = (comp[p + 1] & 15) + 3
                p += 2
                for _ in range(l):
                    if len(o) >= n:
                        break
                    o.append(o[-d])
    return bytes(o)


files = [f for f in order if os.path.exists(os.path.join(src, f))]
files += sorted(f for f in os.listdir(src) if f not in files and not f.startswith('.'))
datas = [open(os.path.join(src, f), 'rb').read().replace(b'\r\n', b'\n') for f in files]
for f in files:
    assert len(f) < 12, f
blob = b''.join(datas)
comp = lzss(blob)
assert unlzss(comp, len(blob)) == blob
o = ['; generated by scripts/gen_examples.py - do not edit',
     '; examples_install() is in firmware/src/shell51.asm',
     '        .module exdata',
     '        .globl  _ex_lz, _ex_dir, _ex_total',
     '        _ex_total = %d' % len(blob),
     '        .area   CONST   (CODE)',
     '_ex_dir:']
for f, d in zip(files, datas):
    o.append('        .asciz  "%s"' % f)
    o.append('        .db     %d, %d' % (len(d) & 0xFF, len(d) >> 8))
o.append('        .db     0')
o.append('_ex_lz:')
for k in range(0, len(comp), 16):
    o.append('        .db     ' + ', '.join('0x%02X' % b for b in comp[k:k + 16]))
open(out, 'w').write('\n'.join(o) + '\n')
print('%d example files, %d bytes, %d compressed' % (len(files), len(blob), len(comp)))
